#[test]
#[allow(clippy::cognitive_complexity)] // One contract keeps the related hash element cases together.
fn hash_elements_preserve_pair_keyword_splat_and_alignment_contracts() {
    let parsed = parse("{ a: 1, **foo }");
    let elements = parsed.ast().unwrap().child_nodes();
    let pair = elements[0];
    let splat = elements[1];
    assert_eq!(pair.kind(), "pair");
    assert_eq!(splat.kind(), "kwsplat");
    assert!(!splat.hash_rocket());
    assert!(!splat.colon());
    assert_eq!(splat.key(), Some(splat));
    assert_eq!(splat.value_node(), Some(splat));
    assert_eq!(splat.operator(), Some("**"));
    assert!(splat.kwsplat_type());

    let parsed = parse("def foo(**)\n  { a: 1, ** }\nend");
    let forwarded = parsed
        .ast()
        .unwrap()
        .body()
        .unwrap()
        .child_nodes()
        .last()
        .copied()
        .unwrap();
    assert!(forwarded.kwsplat_type());
    assert!(forwarded.forwarded_kwrestarg_type());
    assert!(!splat.forwarded_kwrestarg_type());
    assert_eq!(forwarded.key(), Some(forwarded));
    assert_eq!(forwarded.value_node(), Some(forwarded));

    for (source, hash_rocket, colon, delimiter, inverse, omitted, new_line) in [
        ("{ foo => bar }", true, false, "=>", ":", false, false),
        ("{ foo: bar }", false, true, ":", "=>", false, false),
        ("{ foo: }", false, true, ":", "=>", true, false),
        ("{ foo:\n  bar }", false, true, ":", "=>", false, true),
    ] {
        let parsed = parse(source);
        let pair = parsed.ast().unwrap().child_nodes()[0];
        assert_eq!(pair.hash_rocket(), hash_rocket, "{source}");
        assert_eq!(pair.colon(), colon, "{source}");
        assert_eq!(pair.delimiter(false), Some(delimiter), "{source}");
        assert_eq!(pair.inverse_delimiter(false), Some(inverse), "{source}");
        assert_eq!(pair.value_omission(), omitted, "{source}");
        assert_eq!(pair.value_on_new_line(), new_line, "{source}");
    }

    let parsed = parse("{\n  a: 1,\n    bb: 2,\n  **opts\n}");
    let elements = parsed.ast().unwrap().child_nodes();
    assert!(!elements[0].same_line_as(elements[1]));
    assert_eq!(elements[0].key_delta(elements[1], false), -2);
    assert_eq!(elements[0].key_delta(elements[1], true), -3);
    assert_eq!(elements[0].value_delta(elements[1]), -3);
    assert_eq!(elements[0].delimiter_delta(elements[1]), -3);
    assert_eq!(elements[1].key_delta(elements[2], true), 0);
    assert_eq!(elements[1].value_delta(elements[2]), 0);
}

