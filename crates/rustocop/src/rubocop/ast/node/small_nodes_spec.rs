#[test]
fn blocks_expose_arguments_delimiters_dispatch_and_context() {
    for (source, count, first, last) in [
        ("foo { }", 0, None, None),
        ("foo { |q| q }", 1, Some("q"), Some("q")),
        ("foo { |*q| q }", 1, Some("q"), Some("q")),
        ("foo { |q, *z| q }", 2, Some("q"), Some("z")),
        ("foo { |(q, r), (s, t)| q }", 2, None, None),
    ] {
        let parsed = parse(source);
        let node = parsed.ast().unwrap();
        assert_eq!(node.kind(), "block", "{source}");
        assert_eq!(node.arguments().len(), count, "{source}");
        assert_eq!(node.has_arguments(), count > 0, "{source}");
        assert_eq!(
            node.first_argument().and_then(|arg| arg.name()),
            first,
            "{source}"
        );
        assert_eq!(
            node.last_argument().and_then(|arg| arg.name()),
            last,
            "{source}"
        );
    }
    let destructured = parse("foo { |(q, r), (s, t)| q }");
    assert_eq!(
        destructured
            .ast()
            .unwrap()
            .arguments_node()
            .unwrap()
            .argument_list()
            .iter()
            .filter_map(|argument| argument.name())
            .collect::<Vec<_>>(),
        vec!["q", "r", "s", "t"]
    );

    for (source, braces, keywords, delimiters, multiline) in [
        ("foo { work }", true, false, Some(("{", "}")), false),
        ("foo do work end", false, true, Some(("do", "end")), false),
        ("foo do\n work\nend", false, true, Some(("do", "end")), true),
    ] {
        let parsed = parse(source);
        let node = parsed.ast().unwrap();
        assert_eq!(node.braces(), braces, "{source}");
        assert_eq!(node.keywords(), keywords, "{source}");
        assert_eq!(node.delimiters(), delimiters, "{source}");
        assert_eq!(node.multiline(), multiline, "{source}");
        assert_eq!(node.single_line(), !multiline, "{source}");
    }

    let chained_numblock = parse("capture do\n  work\nend.map { _1 }");
    let chained_numblock = chained_numblock.ast().unwrap();
    assert_eq!(chained_numblock.kind(), "numblock");
    assert!(chained_numblock.single_line());
    assert!(!chained_numblock.multiline());

    assert!(parse("-> { work }").ast().unwrap().lambda_block());
    assert!(parse("lambda { work }").ast().unwrap().lambda_block());
    assert!(!parse("foo { work }").ast().unwrap().lambda_block());
    assert!(parse("items.each { work }").ast().unwrap().void_context());
    assert!(parse("items.tap { work }").ast().unwrap().void_context());
    assert!(!parse("items.map { work }").ast().unwrap().void_context());
    assert_eq!(
        parse("foo.bar { work }")
            .ast()
            .unwrap()
            .receiver()
            .unwrap()
            .source(),
        Some("foo")
    );
}

