    pub(crate) fn options(self) -> u32 {
        self.regexp_options()
            .into_iter()
            .fold(0, |options, option| {
                options
                    | match option {
                        'i' => 1,
                        'x' => 2,
                        'm' => 4,
                        'u' => 16,
                        'n' => 32,
                        _ => 0,
                    }
            })
    }

    pub(crate) fn content(self) -> String {
        self.regexp_content()
    }

    pub(crate) fn to_regexp(self) -> Result<regex::Regex, regex::Error> {
        let flags = self
            .regexp_options()
            .into_iter()
            .filter(|option| matches!(option, 'i' | 'm' | 'x'))
            .collect::<String>();
        let content = self.regexp_content();
        regex::Regex::new(&if flags.is_empty() {
            content
        } else {
            format!("(?{flags}){content}")
        })
    }

